/**
 * Generate the retro terminal's virtual file system from content/retro-file-system/.
 *
 * The original Vite project read these files at build time with
 * `import.meta.glob("../file-system/**", { query: "?raw" })`. webpack has no
 * equivalent, so the contents are inlined into a TypeScript module instead.
 * This script is that inlining step — run it whenever the markdown changes:
 *
 *   node scripts/build-file-system.mjs
 *
 * Keys keep the original `../file-system/...` shape because `generateFS`
 * derives each virtual path from them via `path.split("/").slice(2)`. Changing
 * the prefix silently reshapes the whole tree, so leave it alone.
 */
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const SOURCE_DIR = 'content/retro-file-system'
const OUT_FILE = 'app/components/retro/terminal/fileSystemContent.ts'

/** Images are served from public/ rather than inlined; markdown is inlined. */
const IMAGE_PUBLIC_PREFIX = '/retro/images'

/** Every file under dir, recursively, as paths relative to dir. */
function walk(dir, base = dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) return walk(full, base)
    // Finder litters the tree with these and they are not content.
    if (entry === '.DS_Store') return []
    return [relative(base, full)]
  })
}

const files = walk(SOURCE_DIR).sort()
const markdown = files.filter((f) => f.endsWith('.md'))
const images = files.filter((f) => f.endsWith('.png'))

const unknown = files.filter(
  (f) => !markdown.includes(f) && !images.includes(f)
)
if (unknown.length) {
  console.error(
    `Unhandled file types in ${SOURCE_DIR}: ${unknown.join(', ')}\n` +
      'Add a branch for them here, or the terminal will not see them.'
  )
  process.exit(1)
}

const globKey = (file) => `../file-system/${file.split('\\').join('/')}`

const entries = (list, value) =>
  list.map((f) => `  ${JSON.stringify(globKey(f))}: ${value(f)}`).join(',\n')

const out = `/**
 * Static contents of the virtual file system.
 *
 * GENERATED by scripts/build-file-system.mjs — do not hand-edit. Change the
 * markdown in content/retro-file-system/ and re-run:
 *
 *   node scripts/build-file-system.mjs
 *
 * Keys keep the original Vite glob path shape because \`generateFS\` derives the
 * virtual path from them via \`path.split("/").slice(2)\`.
 */

/** Markdown documents, keyed by their original glob path. */
export const markdownFiles: Record<string, string> = {
${entries(markdown, (f) => JSON.stringify(readFileSync(join(SOURCE_DIR, f), 'utf8')))}
}

/** Image files, keyed by glob path, resolving to their public URL. */
export const imageFiles: Record<string, string> = {
${entries(images, (f) => JSON.stringify(`${IMAGE_PUBLIC_PREFIX}/${f.split('/').pop()}`))}
}
`

writeFileSync(OUT_FILE, out)
console.log(
  `Wrote ${OUT_FILE} — ${markdown.length} markdown, ${images.length} image(s).`
)
